import { go } from "@fartlabs/go";

/** ORIGIN is the public origin the redirects are served from. */
export const ORIGIN = "https://go.fart.tools";

/** Cloudflare Workers static assets limits for the `_redirects` file. */
export const MAX_STATIC_REDIRECTS = 2000;
export const MAX_DYNAMIC_REDIRECTS = 100;
export const MAX_RULE_LENGTH = 1000;

/**
 * Aliases are restricted to characters that are literal in a `_redirects`
 * source. This rejects `*`, `:`, spaces, and anything else Cloudflare would
 * interpret as syntax.
 */
const ALIAS_PATTERN = /^[A-Za-z0-9._~-]+(\/[A-Za-z0-9._~-]+)*$/;

export interface RedirectRule {
  source: string;
  destination: string;
  status: number;
}

export interface SkippedEntry {
  alias: string;
  /** "alias" when no rule is emitted at all, "splat" when only subpaths are skipped. */
  kind: "alias" | "splat";
  reason: string;
}

export interface GeneratedRedirects {
  rules: RedirectRule[];
  skipped: SkippedEntry[];
}

/**
 * generateRedirects resolves every alias with `go()` (so chained aliases such
 * as "gh" -> "/github" collapse to their final destination) and returns
 * Cloudflare redirect rules: one exact rule per alias, then one `/alias/*`
 * splat rule per alias so subpaths keep working. Static rules come first and
 * longer aliases win among splats, because Cloudflare applies the first match.
 */
export function generateRedirects(
  links: Record<string, string>,
  status = 302,
): GeneratedRedirects {
  const statics: RedirectRule[] = [];
  const splats: RedirectRule[] = [];
  const skipped: SkippedEntry[] = [];

  for (const alias of Object.keys(links)) {
    if (!ALIAS_PATTERN.test(alias)) {
      throw new Error(`invalid alias ${JSON.stringify(alias)}: use letters, digits, ".", "_", "~", "-" and "/" only`);
    }

    let resolved: URL;
    try {
      resolved = go(new URL(`${ORIGIN}/${alias}`), links);
    } catch (error) {
      throw new Error(`cannot resolve alias ${JSON.stringify(alias)}: ${(error as Error).message}`);
    }

    if (resolved.origin === ORIGIN) {
      skipped.push({
        alias,
        kind: "alias",
        reason: `resolves to this site (${resolved.pathname}), which has no such page`,
      });
      continue;
    }

    statics.push({ source: `/${alias}`, destination: resolved.href, status });

    if (resolved.search || resolved.hash) {
      skipped.push({
        alias,
        kind: "splat",
        reason: "destination has a query or fragment, so subpaths cannot be appended",
      });
      continue;
    }

    splats.push({
      source: `/${alias}/*`,
      destination: `${resolved.href.replace(/\/$/, "")}/:splat`,
      status,
    });
  }

  splats.sort((a, b) => b.source.length - a.source.length || a.source.localeCompare(b.source));

  if (statics.length > MAX_STATIC_REDIRECTS) {
    throw new Error(`${statics.length} static redirects exceeds the limit of ${MAX_STATIC_REDIRECTS}`);
  }
  if (splats.length > MAX_DYNAMIC_REDIRECTS) {
    throw new Error(`${splats.length} dynamic redirects exceeds the limit of ${MAX_DYNAMIC_REDIRECTS}`);
  }

  const rules = [...statics, ...splats];
  for (const rule of rules) {
    if (formatRule(rule).length > MAX_RULE_LENGTH) {
      throw new Error(`redirect for ${rule.source} exceeds ${MAX_RULE_LENGTH} characters`);
    }
  }

  return { rules, skipped };
}

function formatRule(rule: RedirectRule): string {
  return `${rule.source} ${rule.destination} ${rule.status}`;
}

/** formatRedirects renders rules as the contents of a `_redirects` file. */
export function formatRedirects(rules: RedirectRule[]): string {
  return [
    "# Generated by build.ts from links.json. Do not edit.",
    ...rules.map(formatRule),
    "",
  ].join("\n");
}
